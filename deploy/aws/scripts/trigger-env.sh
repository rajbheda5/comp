#!/usr/bin/env bash
# Prints the environment variables for a Trigger.dev Cloud project, ready for
# the dashboard's "Environment Variables → Production → Import .env".
# Tasks run on Trigger.dev's machines, so they need the same secrets as the
# containers plus the public URLs and the (TLS-only) database URL.
#
# Usage (on the server):  scripts/trigger-env.sh app|api > /tmp/trigger-app.env
# Delete the output file after importing it.

set -euo pipefail

PROJECT="${1:-}"
if [ "$PROJECT" != app ] && [ "$PROJECT" != api ]; then
  echo "usage: $0 app|api" >&2
  exit 1
fi

DIR="$(cd "$(dirname "$0")/.." && pwd)"
env_get() { grep -E "^$1=" "$DIR/.env" | tail -1 | cut -d= -f2-; }

APP="https://$(env_get APP_DOMAIN)"
PORTAL="https://$(env_get PORTAL_DOMAIN)"
API="https://$(env_get API_DOMAIN)"
PG_USER="$(env_get POSTGRES_USER)"; PG_USER="${PG_USER:-comp}"
PG_DB="$(env_get POSTGRES_DB)"; PG_DB="${PG_DB:-comp}"

echo "# --- generated by deploy/aws/scripts/trigger-env.sh ($PROJECT project)"
echo "DATABASE_URL=postgresql://${PG_USER}:$(env_get POSTGRES_PASSWORD)@$(env_get DB_DOMAIN):5432/${PG_DB}?sslmode=require"
echo "BASE_URL=$API"
echo "NEXT_PUBLIC_API_URL=$API"
echo "APP_URL=$APP"
echo "NEXT_PUBLIC_APP_URL=$APP"
echo "BETTER_AUTH_URL=$APP"
echo "NEXT_PUBLIC_BETTER_AUTH_URL=$APP"
echo "PORTAL_URL=$PORTAL"
echo "NEXT_PUBLIC_PORTAL_URL=$PORTAL"
echo "NEXT_PUBLIC_SELF_HOSTED=true"
if [ "$PROJECT" = api ]; then
  # API tasks bind/cancel runs in the app project.
  echo "TRIGGER_APP_SECRET_KEY=$(env_get TRIGGER_APP_SECRET_KEY)"
fi
echo
echo "# --- from comp.env"
grep -E '^[A-Z0-9_]+=.+' "$DIR/comp.env"
